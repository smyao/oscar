"""Archive G26-G34/#13-22/#37-49/#69/#126-128/#145/#154/#155; D.4.

Generate an isolated packed STORE clone, preserving rotation/clip/quantization
text. D.4: phase1_stores previously208.6-216.0ms/16K; no history recovery is
added. The only numerical-path change is the destination address. Sidecars
are published by a separate O(N) request-window pass. No timing claim.
"""
from pathlib import Path
import argparse
import hashlib
import json


HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]


def replace_once(text: str, old: str, new: str) -> str:
    if text.count(old) != 1:
        raise ValueError(f"Baseline anchor changed: {old[:80]!r}")
    return text.replace(old, new)


def generate(*, check: bool = False) -> dict:
    baseline = ROOT / "csrc/kernels/rotate_clip_store_striped.cpp"
    source = baseline.read_text()
    shared = ("striped_store_pack.h", "hadamard_indices.h")
    for include in shared:
        if source.count(f'#include "{include}"') != 1:
            raise ValueError(f"Striped writer missing qualified shared helper: {include}")
    for call in ("oscar_striped_store_simd_pack::PackCodes(",
                 "oscar_hadamard_indices_trial::Build("):
        if source.count(call) != 1:
            raise ValueError(f"Striped writer helper call drift: {call}")
    helper_start = source.index("using namespace oscar_ascend_device;")
    store_start = source.index("template <typename T>\nclass RotateStore")
    helper_end = source.index("template <typename T>\nclass RotateOnly")
    helpers = source[helper_start:helper_end]
    store_end = source.index('\n}\n\nextern "C" __global__', store_start)
    store = source[store_start:store_end]
    store = replace_once(store, "class RotateStore", "class RequestPackedStore")
    store = replace_once(store,
        "GM_ADDR slots,GM_ADDR positions,GM_ADDR packed,GM_ADDR rawKey,GM_ADDR rawValue,\n      GM_ADDR tags,GM_ADDR status,",
        "GM_ADDR slots,GM_ADDR positions,GM_ADDR packed,GM_ADDR status,")
    store = replace_once(store,
        "      int64_t kStride,int64_t vStride,int64_t tagStride,int64_t sink,\n      int64_t recent,float kClip,float vClip,bool hadamard)",
        "      float kClip,float vClip,bool hadamard)")
    for line in (
        "    rawK_.SetGlobalBuffer(reinterpret_cast<__gm__ bfloat16_t*>(rawKey));\n",
        "    rawV_.SetGlobalBuffer(reinterpret_cast<__gm__ bfloat16_t*>(rawValue));\n",
        "    tags_.SetGlobalBuffer(reinterpret_cast<__gm__ int64_t*>(tags));\n",
    ):
        store = replace_once(store, line, "")
    store = replace_once(store,
        "    pipe_.InitBuffer(metaBuf_,32); pipe_.InitBuffer(rawBuf_,kMaxDim*2);",
        "    pipe_.InitBuffer(metaBuf_,32);")
    store = replace_once(store,
        "        const int64_t destination=offset+page*pageStride+inPage*heads*headBytes+head*headBytes;",
        "        const int64_t segmentTokens=blockTokens/2;\n"
        "        const int64_t segment=inPage/segmentTokens,within=inPage%segmentTokens;\n"
        "        const int64_t destination=offset+page*pageStride+segment*blocks*pageStride\n"
        "            +(within*heads+head)*headBytes;")
    begin = store.index("        // A later member of the same page/ring")
    end = store.index("\n      }\n      auto localStatus", begin)
    store = store[:begin] + "        // Exact windows have a separate request owner and separate launch." + store[end:]
    begin = store.index("  __aicore__ inline void WriteTag")
    end = store.index("  TPipe pipe_;", begin)
    store = store[:begin] + store[end:]
    store = replace_once(store, "packBuf_,statusBuf_,metaBuf_,rawBuf_;", "packBuf_,statusBuf_,metaBuf_;")
    store = replace_once(store, "slots_,positions_,tags_;", "slots_,positions_;")
    store = replace_once(store, "GlobalTensor<uint8_t> packed_; GlobalTensor<bfloat16_t> rawK_,rawV_;", "GlobalTensor<uint8_t> packed_;")
    header = """// SPDX-License-Identifier: Apache-2.0
// GENERATED by generate.py; do not hand-edit.
// Archive G26-G34/#13-22/#37-49/#69/#126-128/#145/#154/#155.
// D.4 four questions: (1) phase1_stores fused pack; (2) writes208.6-216.0ms
// /16K, dequant6499.8-6655.1ms and host prepare724.7-726.2ms failed;
// (3) retain accepted rotation/clip/FP16 metadata/stripe math verbatim,
// change only final packed address, no history materialization or host loop;
// (4) O(new_tokens*heads*DlogD) Hadamard / O(new_tokens*heads*D^2) dense,
// bounded accepted UB; target below historical215ms, NOT a measurement.
// Source contains no old per-page raw window writes. Same-stream window
// launch consumes completed packed-status output; CPU cannot prove NPU races.
#include "../../kernels/oscar_common.h"
#include "../../kernels/striped_store_pack.h"
#include "../../kernels/hadamard_indices.h"
"""
    footer = """
}
extern "C" __global__ __aicore__ void oscar_request_packed_store_kernel(
    GM_ADDR key,GM_ADDR value,GM_ADDR rk,GM_ADDR rv,GM_ADDR slots,GM_ADDR positions,
    GM_ADDR packed,GM_ADDR status,int64_t tokens,int64_t heads,int64_t dim,
    int32_t dtype,int64_t blockTokens,int64_t blocks,int64_t offset,
    int64_t pageStride,float kClip,float vClip,bool hadamard) {
#define RUN(TYPE) RequestPackedStore<TYPE> op;op.Run(key,value,rk,rv,slots,positions,packed,status,tokens,heads,dim,blockTokens,blocks,offset,pageStride,kClip,vClip,hadamard)
  if(dtype==0){RUN(float);}else if(dtype==1){RUN(half);}else{RUN(bfloat16_t);}
#undef RUN
}
#ifndef ASCENDC_CPU_DEBUG
#include "request_window_launch.h"
namespace oscar_ascend {
void request_packed_store_launch(void* stream,uint32_t grid,void* key,void* value,
    void* rk,void* rv,void* slots,void* positions,void* packed,void* packedStatus,
    int64_t tokens,int64_t heads,int64_t dim,int32_t dtype,int64_t blockTokens,
    int64_t blocks,int64_t offset,int64_t pageStride,float kClip,float vClip,bool hadamard) {
  oscar_request_packed_store_kernel<<<grid,nullptr,stream>>>(
      (GM_ADDR)key,(GM_ADDR)value,(GM_ADDR)rk,(GM_ADDR)rv,(GM_ADDR)slots,
      (GM_ADDR)positions,(GM_ADDR)packed,(GM_ADDR)packedStatus,tokens,heads,dim,
      dtype,blockTokens,blocks,offset,pageStride,kClip,vClip,hadamard);
}
}
#endif
"""
    output = header + helpers + store + footer
    target = HERE / "packed_store.cpp"
    if check:
        if target.read_text() != output:
            raise ValueError("Request-packed writer differs from source transform")
    else:
        target.write_text(output)
    identity = {
        "source": "csrc/kernels/rotate_clip_store_striped.cpp",
        "source_sha256": hashlib.sha256(source.encode()).hexdigest(),
        "writer_optimizations": ["simd_pack", "exact_hadamard_init"],
        "rotation_and_clip_helpers_sha256": hashlib.sha256(helpers.encode()).hexdigest(),
        "shared_helpers_sha256": {name: hashlib.sha256((ROOT / "csrc/kernels" / name).read_bytes()).hexdigest()
                                  for name in shared},
        "generated_sha256": hashlib.sha256(output.encode()).hexdigest(),
        "changes": ["one destination address", "remove per-page exact window publication", "distinct experiment symbol"],
        "CANN": "not_run", "CPU_debug": "not_run", "NPU": "not_run",
    }
    identity_path = HERE / "source_identity.json"
    if check:
        if json.loads(identity_path.read_text()) != identity:
            raise ValueError("Request-packed writer source identity differs")
    else:
        identity_path.write_text(json.dumps(identity, indent=2) + "\n")
    return identity


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    print(json.dumps(generate(check=parser.parse_args().check), indent=2))
