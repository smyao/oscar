def sha(x):return hashlib.sha256(x.encode() if isinstance(x,str) else x).hexdigest()


def generated():
    source=SOURCE.read_text();methods=[];bindings={}
    for name in NAMES:
        a,b=function(source,name)
        marker='  __aicore__ void '+name+'('
        if source.count(marker)!=1:raise ValueError('method declaration changed: '+name)
        start=source.rfind(marker,0,a)
        if start<0:raise ValueError('missing method: '+name)
        exact=source[start:b]
        methods.append(exact);bindings[name]=sha(exact)
    identity={'source':'csrc/experiments/c4_b_nz/c4_candidate.cpp',
              'source_sha256':sha(source),'method_sha256':bindings}
    binding=json.dumps(identity,sort_keys=True)
    content=('// Source binding: '+binding+'\n'
             +'constexpr const char* kPublisherSourceBinding=R"publisher('+binding+')publisher";\n'
             +PREFIX+'\n'.join(methods)+SUFFIX)
    for exact in methods:
        if content.count(exact)!=1:raise ValueError('extracted body is not byte-identical')
    return content,identity


def guarded(path):
    data=path.read_bytes()
    if len(data)!=524288+128 or data[:64]!=b'\xa5'*64 or data[-64:]!=b'\xa5'*64:
        raise ValueError('byte count or guard differs: '+str(path))
    return data[64:-64]


def verify(directory,identity):
    source=guarded(directory/'source.guarded.bin');words=struct.unpack('<131072I',source)
    special=(0,0x80000000,0x7fc00001,0x7fa12345,0x7f800000,0xff800000,1,0x80000001)
    want=tuple(special[i%65536] if i%65536<8 else 0x3f000000+i for i in range(131072))
    if words!=want:raise ValueError('source tags differ')
    for name in ('history','precise'):
        report=json.loads((directory/(name+'.json')).read_text())
        if report.get('status')!='passed' or report.get('checked_words')!=131072:
            raise ValueError('CPU arm did not complete: '+name)
        if report.get('source_binding')!=identity:raise ValueError('compiled method binding differs')
        if guarded(directory/(name+'-source.guarded.bin'))!=source:raise ValueError('input mutated')
        out=struct.unpack('<131072I',guarded(directory/(name+'.guarded.bin')))
        for side in range(2):
            for row in range(256):
                for col in range(256):
                    if out[side*65536+(col//8)*256*8+row*8+col%8]!=words[side*65536+row*256+col]:
                        raise ValueError('independent NZ address mismatch')
    report={'status':'passed','scope':'publisher_only_raw_bits_not_full_C4',
            'source_binding':identity,'modes':['history_old_lane16','precise16'],
            'words_per_mode':131072,'bit_patterns':['signed_zero','qNaN','sNaN','Inf','subnormal','spatial_tags'],
            'CPU':'passed','full_candidate_CPU':'not_established','NPU':'not_run','performance':'not_measured'}
    (directory/'publisher-verification.json').write_text(json.dumps(report,indent=2)+'\n')
    return report


