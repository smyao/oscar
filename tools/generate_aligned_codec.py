def replace(text, old, new, count=1):
    if text.count(old) != count:
        raise ValueError((old[:100], text.count(old), count))
    return text.replace(old, new)

def mother(name):
    path=ROOT/"csrc/kernels"/name
    data=path.read_bytes()
    if hashlib.sha256(data).hexdigest()!=PINS[name]:
        raise ValueError("audited source mother changed: "+name)
    return data.decode()

