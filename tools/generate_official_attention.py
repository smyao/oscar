    text = text.replace("oscar_aligned_cluster_launch.h", "oscar_official_cluster_launch.h")
    # One tuned C16 is the explicit new numerical family. Old control remains
    # registered under its unchanged aligned name in the original binding.
    begin = text.index('  m.def("attention_cv_official_cluster16_control_out(')
    end = text.index(' -> ()");', begin) + len(' -> ()");')
    text = text[:begin] + text[end:]
    lines = [line for line in text.splitlines() if 'm.impl("attention_cv_official_cluster16_control_out"' not in line]
    text = "\n".join(lines) + "\n"
    original = (ROOT / "csrc/attention_bindings.cpp").read_text()
    begin, end = original.index("void Prepare("), original.index("void Attention(")
    prepare = original[begin:end].replace("void Prepare(", "void PrepareOfficial(")
    prepare = prepare.replace("prepare_attention_tasks_launch", "prepare_official_attention_tasks_launch")
    text = replace(text, "template<auto Launch, bool Small", prepare + "template<auto Launch, bool Small")
    begin = original.index('  m.def("prepare_attention_tasks_out(')
    end = original.index(' -> ()");', begin) + len(' -> ()");')
    schema = original[begin:end].replace("prepare_attention_tasks_out", "prepare_official_attention_tasks_out")
    text = replace(text, "TORCH_LIBRARY_FRAGMENT(oscar_ascend_ops,m) {", "TORCH_LIBRARY_FRAGMENT(oscar_ascend_ops,m) {\n" + schema)
