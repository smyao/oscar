@pytest.mark.parametrize("rear", [False, True])
def test_every_install_phase_and_service_receive_budgetless_config(monkeypatch, tmp_path, rear):
    path = tmp_path / "target.json"
    path.write_text(json.dumps(target()))
    before = path.read_bytes()
    logs = tmp_path / "run"
    seen = []

    def check(env):
        config = json.loads(open(env["OSCAR_TARGET_CONFIG"]).read())
        assert "max_num_batched_tokens" not in config
        assert config["use_native_token_budget"] is True
        assert config["experimental_decode_bundle"] is True
        assert config["experimental_whole_prefill"] is False
        assert not config.get("experimental_bounded_whole_prefill", False)
        assert "scheduler_cls" not in config and "history_token_capacity" not in config
        assert config["devices"] == ([4, 5, 6, 7] if rear else [0, 1, 2, 3])
        assert config["port"] == (7878 if rear else 8989)
        return config

    def phase(name, command, *, env, **kwargs):
        check(env)
        if "--config" in command:
            assert command[command.index("--config") + 1] == env["OSCAR_TARGET_CONFIG"]
        seen.append(name)
        return PhaseResult(name, command, 0, 0.0, False, False, str(logs / name), True)

    class Started(Exception):
        pass

    def launch(executable, command, env):
        config = check(env)
        assert seen == list(install_serve.BUILD_PHASES)
        assert command[-1] == env["OSCAR_TARGET_CONFIG"]
        assert "--max-num-batched-tokens" not in serve_argv(config)
        raise Started

    monkeypatch.setattr(install_serve, "run_phase", phase)
    monkeypatch.setattr(install_serve.os, "execvpe", launch)
    with pytest.raises(Started):
        install_serve.main(["--config", str(path), "--log-dir", str(logs),
                            "--variant", "candidate"] +
                           (["--rear-cards"] if rear else []))
    assert path.read_bytes() == before


@pytest.mark.parametrize("script,placement", [
    ("install_serve.sh", []), ("install_serve.sh", ["--rear-cards"]),
    ("install_observe_serve.sh", []),
])
def test_fixed_shell_entrypoints_need_no_native_budget_option(tmp_path, script, placement):
    result = subprocess.run([
        "bash", str(install_serve.ROOT / "scripts" / script), "--variant", "candidate",
        "--plan", "--log-dir", str(tmp_path / "unused"), *placement,
    ], cwd=install_serve.ROOT, env={**os.environ, "OSCAR_PYTHON": sys.executable},
        capture_output=True, text=True, check=True, timeout=20)
    plan = json.loads(result.stdout)
    runtime = plan["runtime_selection"]
    assert runtime["token_budget_source"] == "native"
    assert runtime["max_num_batched_tokens"] is None and runtime["scheduler_cls"] is None
    assert runtime["optimizations"]["whole_prefill"] is False
    assert not runtime["optimizations"].get("bounded_whole_prefill", False)
    assert runtime["optimizations"]["decode_bundle"] is True
    assert runtime["devices"] == ([4, 5, 6, 7] if placement else [0, 1, 2, 3])
    assert runtime["port"] == (7878 if placement else 8989)
    assert not (tmp_path / "unused").exists()


def test_observe_candidate_gates_and_service_share_native_effective_config(monkeypatch, tmp_path):
    source = tmp_path / "target.json"; source.write_text(json.dumps(target()))
    before = source.read_bytes(); logs = tmp_path / "observe"
    seen = []

    def check(path, config, env=None):
        assert path == logs / "effective-target.json"
        assert json.loads(path.read_text()) == config
        if env is not None:
            assert env["OSCAR_TARGET_CONFIG"] == str(path)
        assert config["use_native_token_budget"] is True
        assert not {"max_num_batched_tokens", "scheduler_cls", "history_token_capacity"} & config.keys()
        assert not config.get("experimental_whole_prefill", False)
        assert not config.get("experimental_bounded_whole_prefill", False)
        assert config["experimental_decode_bundle"] is True
        assert config["devices"] == [0, 1, 2, 3] and config["port"] == 8989
        assert "--max-num-batched-tokens" not in serve_argv(config)
        assert "--scheduler-cls" not in serve_argv(config)

    gates = ("_preflight", "_candidate_gate", "_fast_unpack_gate", "_mixed_optimization_gate",
             "_striped_cache_gate", "_decode_bundle_gate", "_mdl_decode_gate", "_current_only_gate",
             "_first_mtp_current_gate", "_mixed_decode_split_gate")
    for name in gates:
        def gate(path, config, env, *_args, name=name):
            check(path, config, env); seen.append(name)
        monkeypatch.setattr(observe_serve, name, gate)

    class ReachedService(RuntimeError):
        returncode = 91
        phase = "test_native_effective_config"

    @contextmanager
    def managed(config, path, **kwargs):
        check(path, config)
        assert kwargs["native"] is False
        assert seen == list(gates)
        seen.append("managed_server")
        raise ReachedService("host test stops before actual device service")
        yield  # pragma: no cover - contextmanager protocol, deliberately no service.

    monkeypatch.setattr(observe_serve, "managed_server", managed)
    monkeypatch.setattr(observe_serve, "read_npu_resources", lambda *args, **kwargs: {})
    monkeypatch.setattr(observe_serve, "wait_for_release", lambda *args, **kwargs: {"status": "passed"})
    monkeypatch.setattr(observe_serve, "_terminal", lambda *args, **kwargs: None)
    assert observe_serve.main(["--config", str(source), "--log-dir", str(logs),
                               "--variant", "candidate"]) == 91
    assert seen[-1] == "managed_server"
    assert source.read_bytes() == before


def native_config(budget, captures):
    return SimpleNamespace(scheduler_config=SimpleNamespace(max_num_batched_tokens=budget),
                           compilation_config=SimpleNamespace(cudagraph_capture_sizes=captures))


@pytest.mark.parametrize("budget,captures,expected", [
    (2048, [128, 512], 2048), (4096, [512], 4096), (1024, [2048], 2048),
])
def test_native_budget_reaches_pre_profile_workspace_without_hardcoding(
        monkeypatch, budget, captures, expected):
    import oscar_ascend.runtime as runtime
    config = selected()
    snapshot = json.dumps(config, sort_keys=True)
    native = native_config(budget, captures)
    module = ModuleType("vllm.config")
    module.get_current_vllm_config = lambda: native
    monkeypatch.setitem(sys.modules, "vllm.config", module)
    provider = NativeTokenBudgetRuntime(config)
    assert not provider.workspaces and "max_num_batched_tokens" not in provider.config
    monkeypatch.setattr(provider, "_device_cube_cores", lambda _: 20)
    monkeypatch.setattr(provider, "_prepare_rotations", lambda *_: None)
    monkeypatch.setattr(runtime, "GraphWorkspace",
                        lambda geometry, device: SimpleNamespace(geometry=geometry, device=device))
    workspace = provider.ensure_workspace(6, 1, 256, "npu:0")
    assert workspace.geometry.tokens == expected
    assert provider.config["max_num_batched_tokens"] == budget
    assert provider.ensure_workspace(6, 1, 256, "npu:0") is workspace
    assert json.dumps(config, sort_keys=True) == snapshot
    assert native.scheduler_config.max_num_batched_tokens == budget
    assert native.compilation_config.cudagraph_capture_sizes == captures
    provider._bind_native_capacity(native_config(budget, []))  # eager MTP has fewer captures
    with pytest.raises(runtime_api.OscarReadinessError, match="changed after"):
        provider._bind_native_capacity(native_config(budget + 128, captures))
    with pytest.raises(runtime_api.OscarReadinessError, match="changed after"):
        provider._bind_native_capacity(native_config(budget, [expected + 128]))


