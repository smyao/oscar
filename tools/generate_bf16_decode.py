"""Generate the explicit BF16 decode reader from the frozen main q4 source.

Archive #126/#145/#148/#154/#157: retain ownership, fail-closed errors and
the frozen FE0 family. D.4: this is bounded fused FIA, never full-history
recovery (the recorded failure cost 6499.8--6655.1 ms). BF16 changes the
operand contract only; FP32 reductions/accumulators and Rv semantics survive.
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "csrc/kernels/attention_cv_hybrid_l1_decode.cpp"
SOURCE_SHA256 = "ffe5a3a5e919e03c631f91f3cdb8b93305e8fe50571f86ab417175b47531d81d"
DESTINATION = ROOT / "csrc/kernels/attention_cv_bf16_decode.cpp"

HEADER = """// SPDX-License-Identifier: Apache-2.0
// Generated by tools/generate_bf16_decode.py from main 7047ce36 q4 finite.
// Archive G4/#126/#145/#148/#154/#157; complete startup D.4 personally read.
// D.4 four questions:
// 1. Fused source0/1/2 decode QK/PV, including MTP q1 and q4.
// 2. Full-history dequant 6499.8--6655.1ms and store209--215ms are forbidden
//    historical failure bounds, not current measured phase percentages.
// 3. Original packed INT2/meta decode and finite/error order stay FP32.
//    Only bounded Q/K/V and each online-exp P tile use RNE BF16 operands;
//    Cube accumulation, max/sum/alpha, normalized partial and LSE stay FP32.
//    Natural BF16 ND publishers and Cube ND2NZ use C0=16, never reinterpret
//    the old FP32 NZ8 buffer. No whole-history tensor or native fallback.
//    Final normalized history and initialization-only natural Rv also use
//    BF16 operands/FP32 accumulation in the same Matmul and flag protocol.
// 4. GM upper bound1146880B/core unchanged, actual operand DMAs use2B.
//    Cast reuses dead natural UB; explicit MTE3_V protects reuse.
//    Complete BF16 oracle/device/graph/performance remain separate gates.
"""


def replace_once(text: str, before: str, after: str) -> str:
    if text.count(before) != 1:
        raise RuntimeError(f"expected one source anchor, got {text.count(before)}: {before[:100]}")
    return text.replace(before, after)


def generate() -> str:
    raw = SOURCE.read_bytes()
    if hashlib.sha256(raw).hexdigest() != SOURCE_SHA256:
        raise RuntimeError("main q4 source changed; BF16 transformation must be reviewed")
    source = raw.decode()
    source = HEADER + source[source.index('#include "oscar_common.h"'):]
    source = source.replace('"attention_hybrid_l1_unpack.h"', '"attention_striped_unpack_padded.h"')
    source = source.replace('"../include/oscar_hybrid_l1_decode_launch.h"', '"../include/oscar_bf16_decode_launch.h"')
    begin = source.index("using Matrix=MatmulType")
    end = source.index("\nstruct Geometry", begin)
    source = source[:begin] + """using Matrix=MatmulType<TPosition::GM,CubeFormat::ND,bfloat16_t,false>;
using TransposedMatrix=MatmulType<TPosition::B1,CubeFormat::NZ,bfloat16_t,true>;
using ResultMatrix=MatmulType<TPosition::GM,CubeFormat::ND,float,false>;
__aicore__ constexpr MatmulConfig CvConfig() {
  auto cfg=GetMDLConfig(false,false,0,false,false,false,true);
  cfg.batchMode=BatchMode::BATCH_LESS_THAN_L1;
  cfg.basicM=64;cfg.basicN=64;cfg.basicK=128;
  cfg.singleCoreM=128;cfg.singleCoreN=256;cfg.singleCoreK=256;
  cfg.enableSetBias=false;
  return cfg;
}
constexpr auto kCubeConfig=GetMatmulApiTiling<Matrix,TransposedMatrix,ResultMatrix,ResultMatrix>(CvConfig());
static_assert(kCubeConfig.baseM==64 && kCubeConfig.baseN==64 && kCubeConfig.baseK==128,
    "BF16 operand contract retains the audited K128 tile order");
static_assert(kCubeConfig.shareL1Size+128*1024<=512*1024,
    "BF16 SDK A1 and external B1 exceed A2 L1");
static_assert(kCubeConfig.shareL0CSize<=128*1024,
    "BF16 FP32 result exceeds A2 L0C");
using CubeMatmul=matmul::MatmulImpl<Matrix,TransposedMatrix,ResultMatrix,ResultMatrix,kCubeConfig>;
""" + source[end:]
    source = replace_once(source, "    rv.SetGlobalBuffer(reinterpret_cast<__gm__ float*>(rotation));",
        "    rv.SetGlobalBuffer(reinterpret_cast<__gm__ bfloat16_t*>(rotation));")
    source = replace_once(source,
        "    work.SetGlobalBuffer(reinterpret_cast<__gm__ float*>(workspace)+core*floatsPerCore);",
        "    work.SetGlobalBuffer(reinterpret_cast<__gm__ float*>(workspace)+core*floatsPerCore);\n"
        "    operands.SetGlobalBuffer(reinterpret_cast<__gm__ bfloat16_t*>(workspace)+core*floatsPerCore*2);")
    source = source.replace("pipe.InitBuffer(externalB,256*1024);", "pipe.InitBuffer(externalB,128*1024);")
    source = source.replace("pipe.InitBuffer(planeBuf,4352);", "pipe.InitBuffer(planeBuf,32);")
    source = source.replace("pipe.InitBuffer(wordIndexBuf,8736);", "pipe.InitBuffer(wordIndexBuf,32);")
    source = source.replace("oscar_direct_nz::", "oscar_ascend_padded_natural::")
    source = replace_once(source, "        metadataIndexBuf,maskBuf,naturalBuf);", "        metadataIndexBuf,maskBuf);")
    begin = source.index("  __aicore__ void Matmul(")
    end = source.index("  __aicore__ int32_t TailColumns", begin)
    source = source[:begin] + """  __aicore__ void Matmul(int64_t a,int64_t b,int64_t c,int32_t m,int32_t n,int32_t k,
      bool rotation=false,bool transposeB=true) {
    // Offsets name the original FP32 arena slots, but operand rows are dense
    // BF16 within each slot. Multiplying only the slot base by2 is essential.
    // Every producer and consumer below uses that same physical contract.
    Fence<HardEvent::MTE1_MTE2>();
    auto localB=externalB.Get<bfloat16_t>();
    Nd2NzParams copy;
    copy.ndNum=1;copy.nValue=transposeB?n:k;copy.dValue=transposeB?k:n;
    copy.srcNdMatrixStride=0;copy.srcDValue=D;
    copy.dstNzC0Stride=256;copy.dstNzNStride=1;copy.dstNzMatrixStride=0;
    if(rotation)DataCopy(localB,rv,copy);else DataCopy(localB,operands[2*b],copy);
    Fence<HardEvent::MTE2_MTE1>();
    mm.SetOrgShape(m,transposeB?kKvRows:D,transposeB?D:kKvRows);
    mm.SetSingleShape(m,n,k);
    mm.SetTensorA(operands[2*a],false);
    mm.SetTensorB(localB,transposeB);
    mm.template IterateAll<true>(work[c]);
    mm.End();
  }
""" + source[end:]
    source = replace_once(source,
        "      DataCopy(work[qOffset+row*D],dst,D);Fence<HardEvent::MTE3_MTE2>();",
        "      auto rounded=operandBuf.Get<bfloat16_t>();\n"
        "      Cast(rounded,dst,RoundMode::CAST_RINT,D);Fence<HardEvent::V_MTE3>();\n"
        "      DataCopy(operands[2*qOffset+row*D],rounded,D);\n"
        "      Fence<HardEvent::MTE3_MTE2>();Fence<HardEvent::MTE3_V>();")
    source = replace_once(source,
        "      DataCopy(work[qOffset+row*D],zeros,count*D);Fence<HardEvent::MTE3_V>();",
        "      auto rounded=operandBuf.Get<bfloat16_t>();\n"
        "      Cast(rounded,zeros,RoundMode::CAST_RINT,count*D);Fence<HardEvent::V_MTE3>();\n"
        "      DataCopy(operands[2*qOffset+row*D],rounded,count*D);Fence<HardEvent::MTE3_V>();")
    source = replace_once(source,
        "    DataCopy(work[(value?vOffset:kOffset)+slot*D],src,kElements);",
        "    auto rounded=operandBuf.Get<bfloat16_t>();\n"
        "    Cast(rounded,src,RoundMode::CAST_RINT,kElements);Fence<HardEvent::V_MTE3>();\n"
        "    DataCopy(operands[2*(value?vOffset:kOffset)+slot*D],rounded,kElements);")
    source = replace_once(source,
        "    DataCopy(work[pOffset+rowBase*kKvRows],scores,activeRows*kKvRows);",
        "    auto rounded=operandBuf.Get<bfloat16_t>();\n"
        "    Cast(rounded,scores,RoundMode::CAST_RINT,activeRows*kKvRows);\n"
        "    Fence<HardEvent::V_MTE3>();\n"
        "    DataCopy(operands[2*pOffset+rowBase*kKvRows],rounded,activeRows*kKvRows);\n"
        "    Fence<HardEvent::MTE3_V>();")
    source = replace_once(source,
        "    DataCopy(work[(value?vOffset:kOffset)+buffer*(2*kKvRows*D)+slot*D],\n        dequantBuf.Get<float>(),kElements);",
        "    auto rounded=operandBuf.Get<bfloat16_t>();\n"
        "    Cast(rounded,dequantBuf.Get<float>(),RoundMode::CAST_RINT,kElements);\n"
        "    Fence<HardEvent::V_MTE3>();\n"
        "    DataCopy(operands[2*((value?vOffset:kOffset)+buffer*(2*kKvRows*D))+slot*D],\n"
        "        rounded,kElements);")
    # Final Rv has the original ownership and flags; only its operands round.
    before="Fence<HardEvent::V_MTE3>();DataCopy(work[qOffset+lane*kLaneRows*D],acc,kLaneRows*D);"
    if source.count(before)!=2:
        raise RuntimeError("both original final-Rv publishers must be present")
    source=source.replace(before,"""auto rounded=naturalBuf.Get<bfloat16_t>();
      Cast(rounded,acc,RoundMode::CAST_RINT,kLaneRows*D);Fence<HardEvent::V_MTE3>();
      DataCopy(operands[2*qOffset+lane*kLaneRows*D],rounded,kLaneRows*D);
      Fence<HardEvent::MTE3_V>();""")
    source = source.replace("GlobalTensor<bfloat16_t> q,ck,cv,wk,wv;", "GlobalTensor<bfloat16_t> q,ck,cv,wk,wv,rv,operands;")
    source = source.replace("GlobalTensor<float> qr,rv,out,outLse,work;", "GlobalTensor<float> qr,out,outLse,work;")
    source = source.replace("operandBuf.Get<bfloat16_t>()", "naturalBuf.Get<bfloat16_t>()")
    source = source.replace("    // Q(128D), K(256D), natural V(256D), score/P(128*256),\n"
        "    // PV/rotation(128D). Query accumulator stays in UB across KV units.\n"
        "    // QK is complete before Vector overwrites score with P; PV is consumed\n"
        "    // before the final Rv rotation reuses that same GM tile. No active aliases.",
        "    // Bounded arena slots retain their FP32 byte bases: BF16 Q32xD,\n"
        "    // BF16 P32x256 in Q-slot's unused upper half, two BF16 K/V256xD\n"
        "    // pairs, FP32 score and FP32 PV32xD. Distinct P/score is essential:\n"
        "    // BF16 P at score's base would cross the two AIV FP32 row owners.")
    source = replace_once(source,
        "    pOffset=scoreOffset;pvOffset=pOffset+kQueryRows*kKvRows;rotOffset=pvOffset;",
        "    static_assert(D==kKvRows,\"Q-slot upper half must fit BF16 P\");\n"
        "    pOffset=kQueryRows*D/2;pvOffset=scoreOffset+kQueryRows*kKvRows;rotOffset=pvOffset;")
    source = source.replace("    // Both K and V are natural [KV,D] FP32. QK requests B transpose=true;\n"
        "    // PV requests false, as permitted by the same static B matmul type.",
        "    // FP32 dequant/finite checks precede the only BF16 RNE publication.\n"
        "    // K/V remain natural [KV,D]; Cube handles the dtype-specific NZ16.")
    source = source.replace("below specify each QK/PV/rotation matrix", "below specify each BF16 QK/PV/Rv matrix")
    source = replace_once(source, "  static constexpr int32_t kPlaneStride=kWords+16;", """  static constexpr int32_t kPlaneStride=kWords+16;
  // SDK TPipe allocations, each rounded to32B; D256 total158656B/AIV.
  static constexpr int32_t kUbBytes=128+2*kHalfKv*kPackedStride+32+
      kHalfKv*(D+16)*2+32+D/8*2+32+32+2*kHalfKv*4+2*kHalfKv*2+
      kElements*4+kHalfRows*kKvRows*4+kLaneRows*D*4+
      D*4+D*2+(2*kLaneRows+2*kHalfRows)*4+kHalfKv*8*4+128;
  static_assert(kUbBytes<=184*1024,"BF16 decode AIV UB exceeds reserved A2 budget");
  static_assert(kHalfKv*(D+16)*2>=kElements*2,"dead natural UB must fit BF16 cast");""")
    source = source.replace("oscar_attention_cv_hybrid_l1_decode_kernel", "oscar_attention_cv_bf16_decode_kernel")
    source = source.replace("attention_cv_hybrid_l1_decode_launch", "attention_cv_bf16_decode_launch")
    source = source.replace("// q1 entrypoint omitted: production retains the separately qualified MDL q1.",
        'extern "C" __global__ __aicore__ void oscar_attention_cv_bf16_decode_q1_kernel(\n'
        '    OSCAR_CV_ARGUMENTS) { OSCAR_CV_RUN(1); }')
    source = source.replace("// q1 launch omitted: hybrid L1 qualification covers q4 only.",
        "OSCAR_STRIPED_LAUNCH(attention_cv_bf16_decode_q1_launch,\n"
        "    oscar_attention_cv_bf16_decode_q1_kernel)")
    return source


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = generate()
    if args.check:
        if DESTINATION.read_text() != text:
            raise SystemExit("BF16 decode source differs from reviewed generation")
    else:
        DESTINATION.write_text(text)


if __name__ == "__main__":
    main()
